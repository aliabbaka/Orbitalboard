"""Refresh explicitly sourced reference facts; never runs in the deployed app.

Raw source snapshots and hashes let reviewers audit the transcribed/generated table.
CIAAW values, not PubChem's differently rounded displayed masses, drive molar masses.
"""
import hashlib
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
PUBCHEM = 'https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON'
CIAAW = 'https://ciaaw.org/abridged-atomic-weights.htm'


class Table(HTMLParser):
    def __init__(self):
        super().__init__(); self.rows = []; self.row = []; self.cell = None
    def handle_starttag(self, tag, attrs):
        if tag == 'tr': self.row = []
        if tag in ('td', 'th'): self.cell = ''
    def handle_data(self, data):
        if self.cell is not None: self.cell += data
    def handle_endtag(self, tag):
        if tag in ('td', 'th') and self.cell is not None:
            self.row.append(' '.join(self.cell.split())); self.cell = None
        if tag == 'tr' and self.row: self.rows.append(self.row)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--offline', action='store_true'); args = parser.parse_args()
    snapshots = ROOT / 'data/reference'; snapshots.mkdir(parents=True, exist_ok=True)
    raw_pub = (snapshots / 'pubchem-periodic.json').read_bytes() if args.offline else urllib.request.urlopen(PUBCHEM, timeout=30).read()
    raw_ciaaw = (snapshots / 'ciaaw-2024.html').read_bytes() if args.offline else urllib.request.urlopen(CIAAW, timeout=30).read()
    table = Table(); table.feed(raw_ciaaw.decode())
    masses = {}
    for row in table.rows:
        if len(row) >= 4 and row[0].isdigit():
            match = re.fullmatch(r'([\d.]+)\s*±\s*([\d.]+)', row[3])
            if match: masses[row[1]] = {'weight': float(match[1]), 'uncertainty': float(match[2]), 'reported': row[3]}
    source = json.loads(raw_pub)['Table']; names = source['Columns']['Column']
    elements = []
    for row in source['Row']:
        data = dict(zip(names, row['Cell'])); symbol = data['Symbol']
        elements.append({'z': int(data['AtomicNumber']), 'symbol': symbol, 'name': data['Name'],
                         'configuration': data['ElectronConfiguration'], 'electronegativity': data['Electronegativity'] or None,
                         'radiusPM': data['AtomicRadius'] or None, 'ionizationEV': data['IonizationEnergy'] or None,
                         'groupBlock': data['GroupBlock'], 'state': data['StandardState'], 'mass': masses.get(symbol)})
    if len(elements) != 118 or len(masses) < 80: raise RuntimeError('Source shape changed; review before importing.')
    (snapshots / 'pubchem-periodic.json').write_bytes(raw_pub)
    (snapshots / 'ciaaw-2024.html').write_bytes(raw_ciaaw)
    metadata = {'pubchemURL': PUBCHEM, 'ciaawURL': CIAAW, 'pubchemSHA256': hashlib.sha256(raw_pub).hexdigest(), 'ciaawSHA256': hashlib.sha256(raw_ciaaw).hexdigest(), 'atomicWeightTable': 'CIAAW Abridged Standard Atomic Weights 2024'}
    (ROOT / 'src/data/periodic.ts').write_text('// Generated by scripts/import_periodic_data.py from the committed source snapshots.\n'
        'export const PERIODIC_METADATA = ' + json.dumps(metadata, indent=2) + ' as const;\n'
        'export const PERIODIC_ELEMENTS = ' + json.dumps(elements, indent=2, ensure_ascii=False) + ' as const;\n')
    print(f'Imported {len(elements)} reference elements and {len(masses)} standard weights.')
